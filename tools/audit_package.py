"""Fail a local build when its archives contain private or generated material.

Run after ``python -m build`` as ``python tools/audit_package.py dist/*``. The scan is a
release gate for common leaks, not a substitute for reviewing the source tree.
"""

from __future__ import annotations

import re
import sys
import tarfile
import zipfile
from pathlib import Path

BLOCKED_PARTS = {
    ".agents",
    ".aws",
    ".git",
    ".mypy_cache",
    ".pytest_cache",
    ".ruff_cache",
    "__pycache__",
    "artifacts",
    "benchmarks",
    "checkpoints",
    "data",
    "datasets",
    "envs",
    "models",
    "scratchpad",
    "work",
}
BLOCKED_SUFFIXES = {
    ".arrow",
    ".ckpt",
    ".feather",
    ".h5",
    ".hdf5",
    ".joblib",
    ".log",
    ".onnx",
    ".parquet",
    ".pickle",
    ".pkl",
    ".pt",
    ".pth",
    ".safetensors",
    ".sqlite",
}
BLOCKED_NAMES = {"agents.md", "pasted text.txt"}
MAX_MEMBER_BYTES = 5_000_000
CONTENT_PATTERNS = {
    "local user path": re.compile(rb"/(?:home|Users)/[^/\s\"']+/|[A-Za-z]:\\Users\\[^\\\s\"']+\\"),
    "temporary session path": re.compile(rb"/tmp/[A-Za-z_-]*[0-9a-f]{16,}/"),
    "AWS access key": re.compile(rb"AKIA[0-9A-Z]{16}"),
    "GitHub token": re.compile(rb"gh[oprsu]_[A-Za-z0-9]{36,}"),
    "API token": re.compile(rb"sk-[A-Za-z0-9]{20,}|sk-proj-[A-Za-z0-9_-]{20,}"),
    "private key": re.compile(rb"-----BEGIN [A-Z ]*PRIVATE KEY-----"),
    "unrequested attribution": re.compile(rb"(?im)^\s*(?:co-authored-by:|generated by)\s*\S+"),
}


def path_issue(name: str) -> str | None:
    path = Path(name)
    parts = {part.lower() for part in path.parts}
    lower = path.name.lower()
    if lower == ".env" or lower.startswith(".env."):
        return "environment secrets file"
    if parts & BLOCKED_PARTS or any(part.startswith(".") for part in path.parts):
        return "generated or private path"
    if path.suffix.lower() in BLOCKED_SUFFIXES:
        return "dataset, weight, cache or temporary file"
    if lower in BLOCKED_NAMES or "prompt" in lower or "private_note" in lower or "draft.md" in lower:
        return "prompt or private note"
    return None


def content_issue(body: bytes) -> str | None:
    for label, pattern in CONTENT_PATTERNS.items():
        if pattern.search(body):
            return label
    return None


def inspect_archive(path: Path) -> tuple[int, list[str]]:
    """Return the number of files inspected and descriptions of findings."""
    findings: list[str] = []
    count = 0
    if path.suffix == ".whl":
        with zipfile.ZipFile(path) as archive:
            for member in archive.infolist():
                if member.is_dir():
                    continue
                count += 1
                issue = path_issue(member.filename)
                if issue:
                    findings.append(f"{member.filename}: {issue}")
                if member.file_size > MAX_MEMBER_BYTES:
                    findings.append(f"{member.filename}: file exceeds {MAX_MEMBER_BYTES} bytes")
                    continue
                issue = content_issue(archive.read(member))
                if issue:
                    findings.append(f"{member.filename}: {issue}")
    elif path.name.endswith(".tar.gz"):
        with tarfile.open(path, "r:gz") as archive:
            for member in archive.getmembers():
                if not member.isfile():
                    continue
                count += 1
                issue = path_issue(member.name)
                if issue:
                    findings.append(f"{member.name}: {issue}")
                if member.size > MAX_MEMBER_BYTES:
                    findings.append(f"{member.name}: file exceeds {MAX_MEMBER_BYTES} bytes")
                    continue
                source = archive.extractfile(member)
                if source is None:
                    findings.append(f"{member.name}: unreadable member")
                    continue
                with source:
                    issue = content_issue(source.read())
                if issue:
                    findings.append(f"{member.name}: {issue}")
    else:
        findings.append("unsupported archive format")
    return count, findings


def main(argv: list[str]) -> int:
    if len(argv) < 2:
        print("usage: python tools/audit_package.py dist/*", file=sys.stderr)
        return 2
    failed = False
    for raw in argv[1:]:
        path = Path(raw)
        if not path.is_file():
            print(f"{path}: missing archive", file=sys.stderr)
            failed = True
            continue
        try:
            count, findings = inspect_archive(path)
        except (OSError, tarfile.TarError, zipfile.BadZipFile) as exc:
            print(f"{path.name}: could not inspect archive ({type(exc).__name__})", file=sys.stderr)
            failed = True
            continue
        print(f"{path.name}: {count} files inspected")
        for finding in findings:
            print(f"FLAG {path.name}: {finding}")
        failed |= bool(findings)
    if not failed:
        print("Package-content audit clean")
    return 1 if failed else 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv))
